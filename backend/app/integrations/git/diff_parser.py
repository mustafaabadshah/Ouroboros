import re
from typing import List, Dict, Any, Tuple, Optional
from app.core.security import is_protected_path

class DiffParseException(Exception):
    pass

class UnifiedDiffParser:
    """
    Parses and inspects Unified Diff formats generated by LLMs or Git.
    Validates file boundaries, lines added/removed, and protected file policies.
    """

    @staticmethod
    def parse_patch(diff_text: str) -> Dict[str, Any]:
        """
        Parses a unified diff string and returns structured metadata:
        - changed_files: List of file paths modified
        - additions: Count of added lines
        - deletions: Count of deleted lines
        - files_details: Per-file breakdown
        - protected_files_touched: List of any protected files detected
        """
        if not diff_text or not diff_text.strip():
            return {
                "is_valid": False,
                "error": "Patch text is empty.",
                "changed_files": [],
                "additions": 0,
                "deletions": 0,
                "files_details": {},
                "protected_files_touched": []
            }

        lines = diff_text.splitlines()
        changed_files = set()
        files_details: Dict[str, Dict[str, int]] = {}
        protected_touched = []

        current_file = None
        additions = 0
        deletions = 0

        # Regex for diff header: --- a/path or +++ b/path
        file_header_re = re.compile(r"^\+\+\+\s+(?:b/)?([^\s\t]+)")

        for line in lines:
            header_match = file_header_re.match(line)
            if header_match:
                raw_path = header_match.group(1).strip()
                if raw_path != "/dev/null":
                    current_file = raw_path.replace("\\", "/")
                    changed_files.add(current_file)
                    if is_protected_path(current_file):
                        protected_touched.append(current_file)
                    files_details.setdefault(current_file, {"additions": 0, "deletions": 0})
                continue

            if current_file:
                if line.startswith("+") and not line.startswith("+++"):
                    additions += 1
                    files_details[current_file]["additions"] += 1
                elif line.startswith("-") and not line.startswith("---"):
                    deletions += 1
                    files_details[current_file]["deletions"] += 1

        is_valid = len(changed_files) > 0 and (additions > 0 or deletions > 0)
        error = None
        if not is_valid:
            error = "Could not identify valid unified diff headers (+++ b/<filepath>) or no modifications found."

        return {
            "is_valid": is_valid,
            "error": error,
            "changed_files": sorted(list(changed_files)),
            "additions": additions,
            "deletions": deletions,
            "files_details": files_details,
            "protected_files_touched": sorted(list(set(protected_touched)))
        }

    @staticmethod
    def validate_patch_boundaries(
        diff_text: str,
        allowed_files: List[str],
        max_lines: int = 500
    ) -> Tuple[bool, Optional[str]]:
        """
        Validates that the patch strictly abides by:
        1. Scope: Only modifies files listed in allowed_files (if allowed_files is specified)
        2. Protected files: Touches no protected files
        3. Size: Total modified lines does not exceed max_lines
        """
        meta = UnifiedDiffParser.parse_patch(diff_text)
        if not meta["is_valid"]:
            return False, meta["error"]

        if meta["protected_files_touched"]:
            return False, f"Prohibited modification of protected files: {meta['protected_files_touched']}"

        total_lines = meta["additions"] + meta["deletions"]
        if total_lines > max_lines:
            return False, f"Patch exceeds maximum allowed line changes ({total_lines} > {max_lines})."

        if allowed_files:
            allowed_normalized = [f.replace("\\", "/").lower() for f in allowed_files]
            for modified in meta["changed_files"]:
                mod_clean = modified.lower()
                if not any(mod_clean.endswith(allow) or allow.endswith(mod_clean) for allow in allowed_normalized):
                    return False, f"Out-of-scope modification: '{modified}' is not in allowed files {allowed_files}."

        return True, None
